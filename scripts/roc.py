#!/usr/bin/env python3
"""Preview, install and check ROC-managed project adapters. No dependencies."""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import sys
import tempfile

KIT = Path(__file__).resolve().parents[1]
TARGETS = {'claude': 'CLAUDE.md', 'codex': 'AGENTS.md',
           'copilot': '.github/copilot-instructions.md'}


def digest(content):
    return hashlib.sha256(content.encode()).hexdigest()


def safe_path(root, relative):
    rel = PurePosixPath(relative)
    if rel.is_absolute() or not rel.parts or any(p in ('..', '.') for p in rel.parts) or '\\' in relative:
        raise ValueError(f'Unsafe path: {relative}')
    p = root
    for index, part in enumerate(rel.parts):
        p = p/part
        if p.is_symlink():
            raise ValueError(f'Symlink refused: {p}')
        if p.exists() and index < len(rel.parts)-1 and not p.is_dir():
            raise ValueError(f'Parent is not a directory: {p}')
    if p.exists() and not p.is_file():
        raise ValueError(f'Expected regular file: {p}')
    if not p.resolve().is_relative_to(root.resolve()):
        raise ValueError(f'Path escapes target: {relative}')
    return p


def render(targets):
    config = json.loads((KIT/'roc.config.json').read_text())
    if config['format_version'] != 1:
        raise ValueError('Unsupported manifest version')
    files = {}
    agreement = (KIT/'templates/project/working-agreement.md').read_text()
    for target in targets:
        files[TARGETS[target]] = ('<!-- Generated by ROC; edit canonical kit sources. -->\n'
                                   + agreement + '\nUse the installed project skills when relevant.\n')
    skill_dirs = set('.claude/skills' if t == 'claude' else '.agents/skills' for t in targets)
    for name, capability in config['capabilities'].items():
        if not name or any(c not in 'abcdefghijklmnopqrstuvwxyz0123456789-' for c in name):
            raise ValueError(f'Invalid capability name: {name}')
        source = safe_path(KIT, capability['source'])
        content = source.read_text()
        for target in targets:
            binding = capability['bindings'][target]
            if binding['status'] != 'shared' or binding['implementation'] != name:
                raise ValueError(f'Unresolved binding: {name}/{target}')
        content += f'\n<!-- ROC source: {capability["source"]}; sha256: {digest(content)} -->\n'
        for directory in skill_dirs:
            files[f'{directory}/{name}/SKILL.md'] = content
    return files


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(dir=path.parent, prefix='.roc-tmp-')
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def run(command, target, targets):
    if target.is_symlink() or not target.is_dir():
        raise ValueError('Target must be an existing, non-symlink project directory')
    target = target.resolve()
    if target == KIT or target.is_relative_to(KIT):
        raise ValueError('Choose a project outside the kit checkout')
    if not targets or set(targets)-TARGETS.keys():
        raise ValueError('Choose targets from claude,copilot,codex')
    if 'copilot' in targets and ('claude' in targets or (target/'.claude/skills').exists()):
        raise ValueError('Ambiguous Copilot skill discovery: use an isolated target without .claude/skills')
    files = render(targets)
    manifest_path = safe_path(target, '.roc/generated.json')
    managed = {}
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text())
        if manifest.get('version') != 1 or not isinstance(manifest.get('files'), dict):
            raise ValueError('Invalid generated-file manifest')
        managed = manifest['files']
        for relative, sha in managed.items():
            safe_path(target, relative)
            if not isinstance(sha, str) or len(sha) != 64:
                raise ValueError('Invalid managed-file hash')
    errors = []
    for relative, content in files.items():
        path = safe_path(target, relative)
        if path.exists():
            current = path.read_text()
            if relative not in managed:
                errors.append(f'Existing user-owned file: {relative}')
            elif digest(current) != managed[relative]:
                errors.append(f'Locally edited generated file: {relative}')
            elif command == 'check' and current != content:
                errors.append(f'Stale output: {relative}')
        elif command == 'check':
            errors.append(f'Missing output: {relative}')
    seeds = {'.roc/context.md': KIT/'templates/project/context.md',
             '.roc/state.md': KIT/'templates/project/state.md'}
    for relative in seeds:
        path = safe_path(target, relative)
        if command == 'check' and not path.is_file():
            errors.append(f'Missing context file: {relative}')
    if errors:
        raise ValueError('\n'.join(errors))
    if command == 'check':
        print('OK: selected adapters match canonical sources')
        return
    for relative in sorted(files):
        print(f'{command}: {relative}')
    if command == 'preview':
        return
    # All collisions and path checks above complete before the first write.
    for relative, content in files.items():
        atomic_write(safe_path(target, relative), content)
        managed[relative] = digest(content)
    for relative, source in seeds.items():
        path = safe_path(target, relative)
        if not path.exists():
            atomic_write(path, source.read_text())
    atomic_write(manifest_path, json.dumps({'version': 1, 'files': managed}, indent=2)+'\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['preview', 'apply', 'check'])
    parser.add_argument('--target', type=Path, required=True)
    parser.add_argument('--targets', help='Comma-separated targets; defaults to roc.config.json')
    args = parser.parse_args()
    try:
        selected = args.targets.split(',') if args.targets else json.loads((KIT/'roc.config.json').read_text())['targets']
        run(args.command, args.target, list(dict.fromkeys(selected)))
    except (ValueError, OSError, KeyError, TypeError) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
